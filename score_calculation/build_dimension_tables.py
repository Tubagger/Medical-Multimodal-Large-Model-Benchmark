#!/usr/bin/env python3
"""Render the five dimension score tables from the 16-task results."""
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / 'score_calculation/results/dimension_scores_current.json'
OUT_TEX = ROOT / 'score_calculation/results/dimension_tables.tex'
OUT_MD = ROOT / 'score_calculation/results/dimension_tables.md'

DIMENSIONS = [
    ('Capability', 'Capability', ['C1', 'C2', 'C3'], 'C'),
    ('Robustness', 'Robustness', ['R1', 'R2', 'R3', 'R4'], 'R'),
    ('Fairness', 'Fairness', ['F1', 'F2'], 'F'),
    ('Privacy', 'Privacy', ['P1', 'P2', 'P3', 'P4'], 'P'),
    ('Safety', 'Safety', ['S1', 'S2', 'S3'], 'S'),
]

GROUPS = [
    ('Medical-Specialized Open-Source MLLMs', 'medicalbar', [
        'Lingshu-7B', 'Lingshu-32B', 'MedGemma-4B', 'MedGemma-27B',
        'Hulu-Med-7B', 'Hulu-Med-32B', 'HuatuoGPT-V-7B',
        'HuatuoGPT-V-34B', 'HealthGPT-Pro-8B',
    ]),
    ('General-Purpose Open-Source MLLMs', 'generalbar', [
        'Qwen3-VL-32B', 'DeepSeek-VL2-Small', 'DeepSeek-VL2',
        'InternVL3.5-14B', 'InternVL3.5-38B', 'GLM-4V-9B',
    ]),
    ('Proprietary MLLMs', 'propbar', [
        'GPT-5.4', 'Gemini-3.5-Flash',
    ]),
]

CAPTIONS = {
    'Capability': (
        'Capability scores across C.1 (Abnormality Detection), '
        'C.2 (Lesion Localization), and C.3 (Medical Reasoning), '
        'with within-dimension rank.'
    ),
    'Robustness': (
        'Robustness scores across R.1 (Out-of-Distribution Medical VQA), '
        'R.2 (Untargeted Adversarial Attack), R.3 (Targeted Adversarial Attack), '
        'and R.4 (Dynamic Response Robustness), with within-dimension rank.'
    ),
    'Fairness': (
        'Fairness scores across F.1 (Unsupported Visual Preference) and '
        'F.2 (Response-Adaptive Medical VQA), with within-dimension rank.'
    ),
    'Privacy': (
        'Privacy scores across P.1 (Medical Privacy Awareness), '
        'P.2 (Image PHI Detection), P.3 (Sensitive-Attribute Inference), '
        'and P.4 (Privacy-Modified Medical VQA), with within-dimension rank.'
    ),
    'Safety': (
        'Safety scores across S.1 (Medical-Risk Request Recognition), '
        'S.2 (MCM Jailbreak), and S.3 (Safety-Modified Medical VQA), '
        'with within-dimension rank.'
    ),
}


def fmt(value):
    return '--' if value is None else f'{value:.2f}'


def rank_map(rows, key):
    ordered = sorted(rows, key=lambda row: row[key], reverse=True)
    return {row['model']: rank for rank, row in enumerate(ordered, 1)}


def column_max(rows, key):
    values = [row[key] for row in rows if row[key] is not None]
    return max(values) if values else None


def cell(value, maximum):
    text = fmt(value)
    if value is not None and maximum is not None and abs(value - maximum) < 1e-9:
        return f'\\textbf{{{text}}}'
    return text


def model_order():
    return [model for _, _, models in GROUPS for model in models]


def rows_by_model():
    rows = json.loads(RESULTS.read_text(encoding='utf-8'))
    by_model = {row['model']: row for row in rows}
    missing = [model for model in model_order() if model not in by_model]
    if missing:
        raise ValueError(f'Missing models in {RESULTS}: {missing}')
    return by_model


def render_tex(by_model):
    lines = [
        '% Generated by score_calculation/build_dimension_tables.py',
        '% Requires xcolor/colortbl (medicalbar, generalbar, propbar) and tabularx.',
        '',
    ]
    for dimension, title, tasks, prefix in DIMENSIONS:
        rows = list(by_model.values())
        ranks = rank_map(rows, dimension)
        maxima = {task: column_max(rows, task) for task in tasks}
        maxima['overall'] = column_max(rows, dimension)
        columns = len(tasks) + 2
        widths = ' '.join([r'>{\centering\arraybackslash}p{0.1\columnwidth}'] * len(tasks))
        lines.extend([
            f'% {title}',
            '\\begin{table}[h]',
            '\\centering',
            f'\\caption{{{CAPTIONS[dimension]}}}',
            f'\\label{{tab:{dimension}_scores}}',
            '',
            '\\fontsize{6.5}{7.3}\\selectfont',
            '\\renewcommand{\\arraystretch}{0.95}',
            '\\setlength{\\tabcolsep}{1.2pt}',
            '',
            '\\begin{tabularx}{\\columnwidth}{',
            '@{}',
            '>{\\raggedright\\arraybackslash}X',
            widths,
            '>{\\centering\\arraybackslash}p{0.25\\columnwidth}',
            '@{}',
            '}',
            '\\toprule',
            '\\textbf{Model} & ' + ' & '.join(f'\\textbf{{{prefix}.{i}}}' for i in range(1, len(tasks) + 1)) + ' &',
            '\\textbf{Dimension mean (rank)} \\\\',
            '\\midrule',
            '',
        ])
        for group_title, color, models in GROUPS:
            lines.append(f'\\rowcolor{{{color}}}')
            lines.append(f'\\multicolumn{{{columns}}}{{@{{}}c@{{}}}}{{\\textbf{{{group_title}}}}} \\\\')
            lines.append('')
            for model in models:
                row = by_model[model]
                cells = [model]
                cells.extend(cell(row[task], maxima[task]) for task in tasks)
                overall = cell(row[dimension], maxima['overall'])
                cells.append(f'{overall} ({ranks[model]})')
                lines.append(' & '.join(cells) + ' \\\\')
            lines.append('')
        lines.extend(['\\bottomrule', '\\end{tabularx}', '\\end{table}', '\\clearpage', '', ''])
    return '\n'.join(lines)


def render_md(by_model):
    lines = ['# Dimension score tables', '']
    for dimension, title, tasks, prefix in DIMENSIONS:
        rows = list(by_model.values())
        ranks = rank_map(rows, dimension)
        maxima = {task: column_max(rows, task) for task in tasks}
        maxima['overall'] = column_max(rows, dimension)
        lines.extend([f'## {title}', '', '| Model | ' + ' | '.join(f'{prefix}.{i}' for i in range(1, len(tasks) + 1)) + ' | Dimension mean (rank) |', '|---|' + '---:|' * len(tasks) + '---:|'])
        for group_title, _, models in GROUPS:
            lines.append(f'| **{group_title}** |' + ' |' * (len(tasks) + 1))
            for model in models:
                row = by_model[model]
                values = []
                for task in tasks:
                    text = fmt(row[task])
                    if row[task] is not None and abs(row[task] - maxima[task]) < 1e-9:
                        text = f'**{text}**'
                    values.append(text)
                overall = fmt(row[dimension])
                if abs(row[dimension] - maxima['overall']) < 1e-9:
                    overall = f'**{overall}**'
                lines.append(f'| {model} | ' + ' | '.join(values) + f' | {overall} ({ranks[model]}) |')
        lines.append('')
    return '\n'.join(lines)


def main():
    by_model = rows_by_model()
    OUT_TEX.write_text(render_tex(by_model), encoding='utf-8')
    OUT_MD.write_text(render_md(by_model), encoding='utf-8')
    print(f'Wrote {OUT_TEX}')
    print(f'Wrote {OUT_MD}')


if __name__ == '__main__':
    main()
